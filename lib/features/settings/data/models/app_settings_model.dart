import 'package:sshub/features/settings/domain/entities/app_settings.dart';

class AppSettingsModel extends AppSettings {
  const AppSettingsModel({
    super.themeMode,
    super.terminalFontSize,
    super.terminalFontFamily,
    super.terminalColorScheme,
    super.terminalScrollback,
    super.cursorStyle,
    super.bellVisual,
    super.bellSound,
    super.copyOnSelect,
    super.pasteOnRightClick,
    super.reduceMotion,
    super.closeSessionOnBack,
    super.appLockEnabled,
    super.lockPasswordReveal,
    super.lockSnippetReveal,
    super.autoLockMinutes,
    super.onboardingComplete,
    super.sftpShowHidden,
    super.sftpGridView,
    super.sftpReadOnly,
    super.defaultPort,
    super.defaultUsername,
    super.downloadDirectory,
    super.blockScreenshots,
  });

  factory AppSettingsModel.fromJson(
    Map<String, dynamic> json,
  ) => AppSettingsModel(
    themeMode:
        AppThemeMode.values.asNameMap()[json['themeMode']] ??
        AppThemeMode.system,
    terminalFontSize: (json['terminalFontSize'] as num?)?.toDouble() ?? 14,
    terminalFontFamily:
        json['terminalFontFamily'] as String? ?? 'JetBrains Mono',
    terminalColorScheme: json['terminalColorScheme'] as String? ?? 'Default',
    terminalScrollback: (json['terminalScrollback'] as num?)?.toInt() ?? 10000,
    cursorStyle: json['cursorStyle'] as String? ?? 'Block',
    bellVisual: json['bellVisual'] as bool? ?? false,
    bellSound: json['bellSound'] as bool? ?? false,
    copyOnSelect: json['copyOnSelect'] as bool? ?? false,
    pasteOnRightClick: json['pasteOnRightClick'] as bool? ?? false,
    reduceMotion: json['reduceMotion'] as bool? ?? false,
    closeSessionOnBack: json['closeSessionOnBack'] as bool? ?? true,
    appLockEnabled: json['appLockEnabled'] as bool? ?? false,
    lockPasswordReveal: json['lockPasswordReveal'] as bool? ?? false,
    lockSnippetReveal: json['lockSnippetReveal'] as bool? ?? false,
    autoLockMinutes: (json['autoLockMinutes'] as num?)?.toInt() ?? 0,
    onboardingComplete: json['onboardingComplete'] as bool? ?? false,
    sftpShowHidden: json['sftpShowHidden'] as bool? ?? false,
    sftpGridView: json['sftpGridView'] as bool? ?? false,
    sftpReadOnly: json['sftpReadOnly'] as bool? ?? true,
    defaultPort: (json['defaultPort'] as num?)?.toInt() ?? 22,
    defaultUsername: json['defaultUsername'] as String? ?? '',
    downloadDirectory: json['downloadDirectory'] as String?,
    blockScreenshots: json['blockScreenshots'] as bool? ?? true,
  );

  Map<String, dynamic> toJson() => {
    'themeMode': themeMode.name,
    'terminalFontSize': terminalFontSize,
    'terminalFontFamily': terminalFontFamily,
    'terminalColorScheme': terminalColorScheme,
    'terminalScrollback': terminalScrollback,
    'cursorStyle': cursorStyle,
    'bellVisual': bellVisual,
    'bellSound': bellSound,
    'copyOnSelect': copyOnSelect,
    'pasteOnRightClick': pasteOnRightClick,
    'reduceMotion': reduceMotion,
    'closeSessionOnBack': closeSessionOnBack,
    'appLockEnabled': appLockEnabled,
    'lockPasswordReveal': lockPasswordReveal,
    'lockSnippetReveal': lockSnippetReveal,
    'autoLockMinutes': autoLockMinutes,
    'onboardingComplete': onboardingComplete,
    'sftpShowHidden': sftpShowHidden,
    'sftpGridView': sftpGridView,
    'sftpReadOnly': sftpReadOnly,
    'defaultPort': defaultPort,
    'defaultUsername': defaultUsername,
    'downloadDirectory': downloadDirectory,
    'blockScreenshots': blockScreenshots,
  };

  factory AppSettingsModel.fromEntity(AppSettings e) => AppSettingsModel(
    themeMode: e.themeMode,
    terminalFontSize: e.terminalFontSize,
    terminalFontFamily: e.terminalFontFamily,
    terminalColorScheme: e.terminalColorScheme,
    terminalScrollback: e.terminalScrollback,
    cursorStyle: e.cursorStyle,
    bellVisual: e.bellVisual,
    bellSound: e.bellSound,
    copyOnSelect: e.copyOnSelect,
    pasteOnRightClick: e.pasteOnRightClick,
    reduceMotion: e.reduceMotion,
    closeSessionOnBack: e.closeSessionOnBack,
    appLockEnabled: e.appLockEnabled,
    lockPasswordReveal: e.lockPasswordReveal,
    lockSnippetReveal: e.lockSnippetReveal,
    autoLockMinutes: e.autoLockMinutes,
    onboardingComplete: e.onboardingComplete,
    sftpShowHidden: e.sftpShowHidden,
    sftpGridView: e.sftpGridView,
    sftpReadOnly: e.sftpReadOnly,
    defaultPort: e.defaultPort,
    defaultUsername: e.defaultUsername,
    downloadDirectory: e.downloadDirectory,
    blockScreenshots: e.blockScreenshots,
  );
}
